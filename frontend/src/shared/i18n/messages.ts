// Releases before English names were added only carry IDs; `hot_air_balloon` reads as "hot air balloon".
export function categoryName(c: Pick<Candidate, 'categoryId' | 'displayNameKo' | 'displayNameEn'>, lang: Lang): string {
  return lang === 'ko' ? c.displayNameKo : c.displayNameEn ?? c.categoryId.replace(/_/g, ' ');
}
